#!/usr/bin/env python3
"""Generate `types/geomancy.d.ts` and `library/dataset/openapi.yaml` from library/schema/.

The schema is the only place a reading is defined; these artefacts are generated so a TS app and a
future HTTP host cannot drift from the Python engine. Run after any schema change (CI does it).
"""
from __future__ import annotations

import json
import re, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "library" / "schema"
OUT_TS = ROOT / "types" / "geomancy.d.ts"
OUT_API = ROOT / "library" / "dataset" / "openapi.yaml"

PRIM = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}


def ts_type(node, ctx, name_hint="T"):
    if not isinstance(node, dict):
        return "unknown"
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    if "anyOf" in node or "oneOf" in node:
        return " | ".join(ts_type(x, ctx) for x in (node.get("anyOf") or node.get("oneOf")))
    t = node.get("type")
    if isinstance(t, list):
        return " | ".join(PRIM.get(x, "unknown") for x in t)
    if t == "object" or "properties" in node:
        key = name_hint
        if key and key not in ctx:
            props = node.get("properties") or {}
            req = set(node.get("required") or [])
            fields = []
            ctx[key] = None
            for k, v in props.items():
                if k == "properties" and isinstance(v, dict) and set(v) <= set(json.dumps(v)):
                    pass
                fields.append(f"  {'readonly ' if False else ''}{json_safe(k)}{'?' if k not in req else ''}: {ts_type(v, ctx, key + camel('_' + k))};")
            for k, v in (node.get("patternProperties") or {}).items():
                fields.append(f"  [key: string]: {ts_type(v, ctx, key + 'Entry')};")
            addl = node.get("additionalProperties")
            if isinstance(addl, dict):
                fields.append(f"  [key: string]: {ts_type(addl, ctx, key + 'Value')};")
            ctx[key] = "\n".join(fields) or "  [key: string]: unknown;"
        return key if key in ctx and ctx[key] else "Record<string, unknown>"
    if t == "array":
        inner = ts_type(node.get("items"), ctx, name_hint + "Item")
        return f"{inner}[]" if " " not in inner and "|" not in inner else f"({inner})[]"
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    return PRIM.get(t, "unknown")


def json_safe(k):
    return k if k.isidentifier() else json.dumps(k)


def camel(s: str) -> str:
    # Identifiers, not prose. This used to prefer each schema's `title` as the interface name, and titles are
    # sentences - the shipped types/geomancy.d.ts carried `export interface A passage in the library: text is
    # never allowed without provenance`, which no TypeScript compiler can read. Names now come from the file
    # stem, sanitised, and titles become doc comments.
    words = [w for w in re.split(r"[^A-Za-z0-9]+", s or "") if w]
    return "".join(w.capitalize() for w in words) or "Generated"


def main() -> int:
    ctx, blocks = {}, []
    for f in sorted(SCHEMA.glob("*.json")):
        sch = json.loads(f.read_text())
        name = camel(f.stem)
        title = " ".join(str(sch.get("title") or "").split())
        if sch.get("type") == "array":
            inner = ts_type(sch.get("items"), ctx, name + "Item")
            blocks.append(f"export type {name}Item = {inner};")
            blocks.append(f"export type {name} = {name}Item[];")
            continue
        root = ts_type(sch, ctx, name)
        blocks.append(f"/** generated from library/schema/{f.name} - do not edit */"
                      + (f"\n *\n * {title}" if title else "") + "\n */" if False else
                      f"/** generated from library/schema/{f.name} - do not edit.\n"
                      + (f" * {title}\n" if title else "") + " */")
        for k, body in ctx.items():
            if body and k not in [b.split(" ")[2] for b in blocks if b.startswith("export interface")]:
                blocks.append(f"export interface {k} {{\n{body}\n}}")
                ctx[k] = ""
        if root != name:
            blocks.append(f"export type {name} = {root};")
    seen, out = set(), []
    for b in blocks:
        key = b[:60]
        if key in seen:
            continue
        seen.add(key)
        out.append(b)
    OUT_TS.parent.mkdir(parents=True, exist_ok=True)
    OUT_TS.write_text("// generated by library/tools/gen_types.py - the reading contract for TS/Swift apps\n"
                      "// Source of truth: library/schema/*.json. Regenerate with `make types`.\n\n"
                      + "\n\n".join(out) + "\n")
    n_iface = OUT_TS.read_text().count("export interface")
    manifest = {}
    mf = ROOT / "library" / "dataset" / "manifest.json"
    if mf.exists():
        manifest = json.loads(mf.read_text())
    OUT_API.write_text(f"""openapi: 3.1.0
info:
  title: geomancy-library data API
  version: {json.dumps(manifest.get('version', '0.2.0'))}
  description: >
    Static-first contract. Every response below is a file already present under
    library/dataset/, so an app can be shipped as a bundle download with no server at all;
    hosting these paths behind any CDN is a drop-in upgrade (files are content-addressed in
    bundles.json, so cache-busting is free).
  license: {{name: CC BY 4.0 (data), MIT (code), url: https://github.com/Almuarif17/geomancy/blob/main/LICENSE}}
paths:
  /reading:
    get:
      summary: compute a full reading for four Mothers and an outcome
      parameters:
      - {{in: query, name: mothers, required: true, schema: {{type: string}}, description: four figure names, comma separated, in house order I..IV}}
      - {{in: query, name: topic, required: false, schema: {{type: string}}, description: one of the outcome keys in index/by_outcome.jsonl}}
      - {{in: query, name: day, required: false, schema: {{type: string}}, description: weekday of the cast, for the planetary-hour gate}}
      - {{in: query, name: hour, required: false, schema: {{type: integer}}, description: temporal planetary hour 1-12 from sunrise}}
      responses:
        '200':
          description: the reading contract (see types/geomancy.d.ts)
          content: {{application/json: {{schema: {{$ref: '#/components/schemas/Reading'}}}}}}
  /index/by_outcome.jsonl:
    get: {{summary: one row per answerable outcome - house, routing, rulings, base rates, passage ids, rules to apply,
            responses: {{'200': {{content: {{application/x-ndjson: {{schema: {{type: string}}}}}}}}}}}}
  /index/by_figure.jsonl:
    get: {{summary: per figure: pattern, attributes, judge attainability, 12 house rulings, passage ids,
            responses: {{'200': {{content: {{application/x-ndjson: {{schema: {{type: string}}}}}}}}}}}}
  /index/by_house.jsonl:
    get: {{summary: per house: latin/english scope, folio, figure rulings, perfection base rates,
            responses: {{'200': {{content: {{application/x-ndjson: {{schema: {{type: string}}}}}}}}}}}}
  /bundles.json:
    get: {{summary: which files each app screen must download, with bytes + sha256,
            responses: {{'200': {{content: {{application/json: {{schema: {{type: object}}}}}}}}}}}}
components:
  schemas:
    Reading:
      description: generated from library/schema/reading.json ({n_iface} interfaces in types/geomancy.d.ts)
""")
    print(f"types: {OUT_TS.relative_to(ROOT)} ({n_iface} interfaces) | api: {OUT_API.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
