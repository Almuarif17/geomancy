#!/usr/bin/env python3
"""Validate the published artefacts against the schemas in library/dataset/schema/.

The contract is only real if it is checked: this is what stops a new extract from silently shipping a
passage without a locator, or a reader that no longer satisfies the app-facing schema.
"""
import json, pathlib, re, sys
try:
    import jsonschema
except ImportError:
    print("jsonschema missing: pip install jsonschema"); sys.exit(2)
LIB = pathlib.Path(__file__).resolve().parents[1]   # .../library
ROOT = LIB.parent
ok = True
psh = json.loads((LIB / "schema/passage.json").read_text())
rows = [json.loads(l) for l in (LIB / "dataset/shards/passages.jsonl").read_text().splitlines() if l.strip()]
bad = 0
for r in rows:
    try: jsonschema.validate(r, psh)
    except Exception as e:
        bad += 1
        if bad <= 3: print("passage invalid:", str(e)[:130])
print(f"passages: {len(rows)} checked, {bad} invalid")
ok &= bad == 0
rp = LIB / "schema/reading.json"
if rp.exists():
    sch = json.loads(rp.read_text())
    for name in (str(ROOT / "examples" / "reading.example.json"),):
        f = pathlib.Path(name)
        if not f.exists():
            continue
        try:
            jsonschema.validate(json.loads(f.read_text()), sch); print(f"reading {name}: valid")
        except Exception as e:
            ok = False; print(f"reading {name}: INVALID - {str(e)[:200]}")

# rules + manifest + the outcome indexes the app reads
import json as _j
rf = LIB / "schema/rule.json"
if rf.exists():
    rsch = _j.loads(rf.read_text()); bad = 0; n = 0
    rp = LIB / "dataset/shards/rules.jsonl"
    if rp.exists():
        for l in rp.read_text().splitlines():
            if not l.strip(): continue
            n += 1
            try: jsonschema.validate(_j.loads(l), rsch)
            except Exception as e:
                bad += 1
                if bad <= 3: print("rule invalid:", str(e)[:130])
        print(f"rules: {n} checked, {bad} invalid"); ok &= bad == 0
    mf = LIB / "dataset/manifest.json"
    if mf.exists():
        try:
            jsonschema.validate(_j.loads(mf.read_text()), _j.loads((LIB / "schema/manifest.json").read_text()))
            print("manifest: valid")
        except Exception as e:
            ok = False; print("manifest INVALID:", str(e)[:160])
for name in ("by_figure", "by_house", "by_outcome"):
    f = LIB / "dataset/index" / f"{name}.jsonl"
    if not f.exists():
        ok = False; print(f"index/{name}.jsonl: MISSING - run `python3 engine/retrieve.py --build`")
        continue
    rows = [_j.loads(l) for l in f.read_text().splitlines() if l.strip()]
    empty = sum(1 for r in rows if not any(v for v in r.values()))
    print(f"index/{name}.jsonl: {len(rows)} rows, {empty} wholly empty")
    ok &= bool(rows) and empty == 0
    # by_outcome is the one index with a published row contract (schema/outcome_row.json, generated by the
    # same build that writes the data), so the contract is checked two ways: every row validates against it,
    # and no key appears in the data or the contract without also appearing in the other. An app that codes
    # against types/geomancy.d.ts must never find a field that is not there, and never miss one that is.
    sf = LIB / "schema" / "outcome_row.json"
    if name == "by_outcome" and sf.exists():
        sch = _j.loads(sf.read_text())
        keys = set().union(*[set(r) for r in rows]) if rows else set()
        declared = set(sch.get("properties", {}))
        if keys - declared:
            ok = False; print(f"  CONTRACT DRIFT: index rows carry keys the schema never declares: {sorted(keys - declared)[:6]}")
        if declared - keys:
            ok = False; print(f"  CONTRACT DRIFT: schema declares keys no row has: {sorted(declared - keys)[:6]}")
        try:
            import jsonschema
            v = jsonschema.Draft202012Validator(sch)
            bad = next(iter([f"row {i}: {e.message}" for i, r in enumerate(rows)
                             for e in [next(iter(v.iter_errors(r)), None)] if e]), None)
            if bad:
                ok = False; print(f"  outcome rows INVALID against schema/outcome_row.json -> {bad}")
            else:
                print(f"  outcome_row contract: {len(declared)} keys, {len(rows)} rows validate, "
                      f"data and contract agree both ways")
        except ImportError:
            print("  (jsonschema absent: contract validated by key-set comparison only)")
# The published TypeScript contract is generated, and generated files are only trustworthy if something
# reads them: this .d.ts shipped for two releases with an interface named after a whole sentence, because no
# gate ever parsed it. These are the checks a compiler would run - valid identifiers, one declaration per
# name, balanced braces, and no reference to a type that is not declared.
ts = ROOT / "types" / "geomancy.d.ts"
if ts.exists():
    txt = ts.read_text()
    names = re.findall(r"^export (?:interface|type) ([^\s{=]+)", txt, re.M)
    bad_names = [n for n in names if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n)]
    dupes = sorted({n for n in names if names.count(n) > 1})
    refs = set(re.findall(r":\s*\??\s*([A-Z][A-Za-z0-9_]*)", txt)) | set(
        re.findall(r"\[\]\s*;", txt) and [])
    declared = set(names)
    builtin = {"string", "number", "boolean", "null", "unknown", "any", "true", "false"}
    dangling = sorted(r for r in refs if r not in declared and r.lower() not in builtin and r[0].isupper())
    bal = txt.count("{") - txt.count("}")
    if bad_names:
        ok = False; print(f"types/geomancy.d.ts: INVALID identifier(s) {bad_names[:3]}")
    if dupes:
        ok = False; print(f"types/geomancy.d.ts: duplicate declarations {dupes[:4]}")
    if bal:
        ok = False; print(f"types/geomancy.d.ts: unbalanced braces ({bal:+d})")
    if dangling:
        ok = False; print(f"types/geomancy.d.ts: references undeclared type(s) {dangling[:4]}")
    if not (bad_names or dupes or bal or dangling):
        print(f"types/geomancy.d.ts: {len(names)} declarations, all valid identifiers, nothing dangling")
else:
    ok = False
    print("types/geomancy.d.ts: MISSING - run `python3 library/tools/gen_types.py`")

print("SCHEMA CHECKS " + ("PASS" if ok else "FAIL"))
sys.exit(0 if ok else 1)
